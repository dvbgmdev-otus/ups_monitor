/**
 * @file fs_utils.h
 * @ingroup utils
 * @brief Утилиты для работы с файловой системой.
 *
 * Содержит функции для работы с путями относительно каталога бинарника.
 */
#ifndef FS_UTILS_H
#define FS_UTILS_H

#include <string>

namespace utils {

/**
 * @brief Преобразует путь в абсолютный относительно каталога бинарника.
 *
 * Если путь начинается с '/', возвращается без изменений.
 * В противном случае путь вычисляется относительно каталога бинарника.
 *
 * @warning Функция не выполняет нормализацию пути
 *          (не обрабатывает "..", ".", двойные слеши и т.п.).
 *
 * @param path Относительный или абсолютный путь.
 * @return Абсолютный путь.
 */
std::string resolvePath(const std::string& path);

}  // namespace utils

#endif  // FS_UTILS_H
